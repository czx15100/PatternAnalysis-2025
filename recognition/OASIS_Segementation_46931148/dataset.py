"""
OASIS Dataset Loader for Brain MRI Segmentation
"""

import os
from typing import Tuple
from PIL import Image
import numpy as np
import torch
from torch.utils.data import Dataset
import torchvision.transforms.functional as TF
import random

class OASISDataset(Dataset):
    """
    Custom PyTorch Dataset for the OASIS MRI Segmentation Dataset.
    """
    def __init__(self, images_dir: str, masks_dir: str, sort_key=None):
        super().__init__()
        self.images_dir = images_dir
        self.masks_dir = masks_dir
        self.sort_key = sort_key

        # List all sorted image and mask files
        self.image_files = sorted(
            [f for f in os.listdir(self.images_dir) if not f.startswith(".")],
            key=self.sort_key
        )
        self.mask_files = sorted(
            [f for f in os.listdir(self.masks_dir) if not f.startswith(".")],
            key=self.sort_key
        )

    def __len__(self) -> int:
        """Return the total number of image-mask pairs."""
        return len(self.image_files)

    def __getitem__(self, idx: int) -> Tuple[torch.Tensor, torch.Tensor]:
        """
        Load and return an image-mask pair
        """
        # Load image and mask
        img_path = os.path.join(self.images_dir, self.image_files[idx])
        mask_path = os.path.join(self.masks_dir, self.mask_files[idx])
        img_pil = Image.open(img_path).convert("L")  # grayscale
        mask_pil = Image.open(mask_path)

        # Convert to numpy arrays
        image_np = np.asarray(img_pil, dtype=np.float32) / 255.0
        mask_np = np.asarray(mask_pil, dtype=np.int64)

        # Map mask pixel intensities to class IDs
        mask_np[mask_np == 85] = 1
        mask_np[mask_np == 170] = 2

        # Convert to tensors
        image_t = torch.from_numpy(image_np).unsqueeze(0)
        mask_t = torch.from_numpy(mask_np).long()

        # Data augmentation
        if random.random() < 0.5:
            # Flip horizontally
            image_t = TF.hflip(image_t)
            mask_t = TF.hflip(mask_t)
        if random.random() < 0.3:
            # Rotate
            # Interplolation generated by ChatGPT
            angle = random.uniform(-5, 5)
            image_t = TF.rotate(image_t, angle)
            mask_t = TF.rotate(mask_t.unsqueeze(0).float(), angle, interpolation=TF.InterpolationMode.NEAREST).squeeze(0).long()
        if random.random() < 0.3:
            # Adjust brightness and contrast
            image_t = TF.adjust_brightness(image_t, random.uniform(0.95, 1.05))
            image_t = TF.adjust_contrast(image_t, random.uniform(0.95, 1.05))
        if random.random() < 0.2:
            # Add Gaussian noise
            noise = torch.randn_like(image_t) * 0.01
            image_t = torch.clamp(image_t + noise, 0, 1)

        return image_t, mask_t